// Description  : This module is used to transfer pulse from one clock domain to
//                to other clock domain.
//-----------------------------------------------------------------------------
module ahbl_to_lmmi_inst_ipgen_pulse_sync (
    input inclk, 
    input outclk, 
    input inclk_reset_n, 
    input outclk_reset_n, 
    input indata_i, 
    output outdata_o) ;
    // Unit delay parameter for Simulation purpose.
    parameter UD = 1 ; 
    reg indata_f ; 
    reg outdata_f1 ; 
    reg outdata_f2 ; 
    reg outdata_f3 ; 
    //------..-----..-----..-----..-----..-----..-----..-----..-----..-----..-----
    //                Read this before you begin,
    // This method is used only to synchronize pulse of 1 clock duration when it passes
    // clock domain.
    // In other words, indata_i must ( must again ) be a pulse of 1 clock ( inclk )duration.
    // It's better if indata_i is an output of a flip-flop.
    //------..-----..-----..-----..-----..-----..-----..-----..-----..-----..-----
    //  Input T flip Flop design
    always
        @(posedge inclk or 
            negedge inclk_reset_n)
        if ((~inclk_reset_n)) 
            indata_f <= #(UD)   1'b0 ;
        else
            if (indata_i) 
                // for active low input pulse comment this line and remove comment from below line
                //if(~indata_i)
                indata_f <= #(UD)   (~indata_f) ;
    // Flop indata_i using outclk
    always
        @(posedge outclk or 
            negedge outclk_reset_n)
        if ((~outclk_reset_n)) 
            outdata_f1 <= #(UD)   1'b0 ;
        else
            outdata_f1 <= #(UD)   indata_f ;
    // Flop indata_i using outclk
    always
        @(posedge outclk or 
            negedge outclk_reset_n)
        if ((~outclk_reset_n)) 
            outdata_f2 <= #(UD)   1'b0 ;
        else
            outdata_f2 <= #(UD)   outdata_f1 ;
    // Flop indata_i using outclk
    always
        @(posedge outclk or 
            negedge outclk_reset_n)
        if ((~outclk_reset_n)) 
            outdata_f3 <= #(UD)   1'b0 ;
        else
            outdata_f3 <= #(UD)   outdata_f2 ;
    assign outdata_o = (outdata_f2 ^ outdata_f3) ; // for active low input pulse comment this line and remove comment from below line

//assign outdata_o = ~(outdata_f2 ^ outdata_f3);
endmodule



