// Description  : This module is used for synchronizing the multi bit data with
//                the use of synchronized pulse and acknowledged pulse is
//                returned. This technique is known as Multi Cycle Path (MCP)
//                Formulation with acknowledged feedback.
//-----------------------------------------------------------------------------
module ahbl_to_lmmi_inst_ipgen_sync_mcp_ack_fdbk (
    input inclk,  // clock signal of sending clock domain
    input inclk_reset_n,  // reset signal synchronized with "inclk"
    input indata_send_pl_i,  // send pulse
    output inclk_ack_pl_o,  // ready signal ( ACK is received from "outclk" domain )
    input outclk,  // clock signal of receiving clock domain
    input outclk_reset_n,  // reset signal synchronized with "outclk"
    input outclk_data_ld_i,  // load signal synchronized with "outclk"
    output outdata_ld_pl_o // load pulse synchronized with "outclk"
        ) ;
    //===================================================
    //
    // Parameter Declaration
    //
    //===================================================
    // Unit delay parameter for Simulation purpose.
    parameter UD = 1'b1 ; 
    //=====================================================================================
    //
    // Instance of "pulse_sync" module.
    //
    // This module will synchronize the "indata_send_pl_i" pulse with "out_clk" which is
    // read request from the avalon master side.
    //
    //======================================================================================
    ahbl_to_lmmi_inst_ipgen_pulse_sync ubps1 (.inclk(inclk), 
                .outclk(outclk), 
                .inclk_reset_n(inclk_reset_n), 
                .outclk_reset_n(outclk_reset_n), 
                .indata_i(indata_send_pl_i), 
                .outdata_o(outdata_ld_pl_o)) ; 
    //==========================================================================================
    //
    //    Instance of "pulse_sync" module.
    //
    // -> The purpose of this instance is to provide the "u_read_data_valid" pulse to "inclk"
    //    domain with "read data".
    //
    // -> So this pulse synchronizer will take this pulse and generate "inclk_ack_pl_o"
    //    pulse synchronized with "inclk" domain.
    //
    // -> "inclk_ack_pl_o" will be used to de assert wait request signal.
    //
    //===========================================================================================
    ahbl_to_lmmi_inst_ipgen_pulse_sync ubps2 (.inclk(outclk), 
                .outclk(inclk), 
                .inclk_reset_n(outclk_reset_n), 
                .outclk_reset_n(inclk_reset_n), 
                .indata_i(outclk_data_ld_i), 
                .outdata_o(inclk_ack_pl_o)) ; 
endmodule


